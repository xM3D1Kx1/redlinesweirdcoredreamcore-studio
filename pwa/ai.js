/* DREZZDON — умный анализ через Gemini.
 *
 * Подключается к drezzdon_studio.html после основного скрипта.
 * Кнопка «⚡ Авто-генерация (Умный анализ)» вызывает smartAnalyze():
 *   1. уменьшает фото и отправляет на локальный сервер (/api/analyze)
 *   2. сервер спрашивает Gemini, ключ остаётся на сервере
 *   3. ответ превращается в перетаскиваемые рамки, подписи и пунктиры
 *   4. если Gemini недоступен — тихо откатывается на локальный движок
 */
(function () {
  'use strict';

  var localGenerate = window.autoGenerateDrezzdon; // исходный локальный генератор
  var busy = false;

  /* ------------------------------ утилиты ------------------------------ */

  function clamp(v, a, b) {
    return Math.max(a, Math.min(b, v));
  }

  function sanitize(s) {
    return String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
  }

  var toastEl = null;
  var toastTimer = null;

  function toast(msg, kind, ms) {
    if (!toastEl) {
      toastEl = document.createElement('div');
      toastEl.style.cssText =
        'position:fixed;left:50%;bottom:96px;transform:translateX(-50%);z-index:99;' +
        'max-width:min(560px,90vw);padding:10px 16px;border-radius:10px;' +
        'font:600 13px/1.4 Inter,Arial,sans-serif;text-align:center;pointer-events:none;' +
        'background:rgba(12,12,16,.94);border:1px solid rgba(255,30,30,.55);' +
        'color:#f0f0f5;box-shadow:0 8px 30px rgba(0,0,0,.6);transition:opacity .25s ease;';
      document.body.appendChild(toastEl);
    }
    toastEl.textContent = msg;
    toastEl.style.opacity = '1';
    if (kind === 'warn') {
      toastEl.style.borderColor = 'rgba(255,170,30,.65)';
      toastEl.style.color = '#ffd9a0';
    } else {
      toastEl.style.borderColor = 'rgba(255,30,30,.55)';
      toastEl.style.color = '#f0f0f5';
    }
    clearTimeout(toastTimer);
    if (ms !== 0) {
      toastTimer = setTimeout(function () {
        toastEl.style.opacity = '0';
      }, ms || 3200);
    }
  }

  function hideToast() {
    clearTimeout(toastTimer);
    if (toastEl) toastEl.style.opacity = '0';
  }

  /* ------------------------- подготовка картинки ------------------------- */

  function compressImage(img, maxSide, quality) {
    var w = img.width || img.naturalWidth;
    var h = img.height || img.naturalHeight;
    var scale = Math.min(1, maxSide / Math.max(w, h));
    var cw = Math.max(1, Math.round(w * scale));
    var ch = Math.max(1, Math.round(h * scale));
    var off = document.createElement('canvas');
    off.width = cw;
    off.height = ch;
    var octx = off.getContext('2d');
    octx.fillStyle = '#000';
    octx.fillRect(0, 0, cw, ch);
    octx.drawImage(img, 0, 0, cw, ch);
    return off.toDataURL('image/jpeg', quality || 0.85);
  }

  /* ---------------------- ответ Gemini -> элементы ---------------------- */

  function buildElements(analysis) {
    var W = canvas.width;
    var H = canvas.height;
    var out = [];
    var byId = {};

    var dets = Array.isArray(analysis && analysis.detections) ? analysis.detections.slice(0, 6) : [];

    dets.forEach(function (d, i) {
      var b = d && d.box_2d;
      if (!Array.isArray(b) || b.length !== 4) return;
      var ymin = Number(b[0]), xmin = Number(b[1]), ymax = Number(b[2]), xmax = Number(b[3]);
      if (!isFinite(ymin + xmin + ymax + xmax)) return;

      var x = (Math.min(xmin, xmax) / 1000) * W;
      var y = (Math.min(ymin, ymax) / 1000) * H;
      var w = (Math.abs(xmax - xmin) / 1000) * W;
      var h = (Math.abs(ymax - ymin) / 1000) * H;

      w = clamp(w, W * 0.045, W * 0.92);
      h = clamp(h, H * 0.03, H * 0.92);
      x = clamp(x, 6, W - w - 6);
      y = clamp(y, 6, H - h - 6);

      var caption = sanitize(d.caption || d.label || '');
      if (caption.length > 40) caption = caption.slice(0, 39) + '…';

      var el = {
        type: 'aiBox',
        x: x,
        y: y,
        w: w,
        h: h,
        caption: caption,
        graphic: d.graphic_type || 'box_with_arrow',
        side: d.preferred_label_side || 'bottom',
        index: i + 1,
        confidence: d.confidence,
        fromAi: true
      };
      out.push(el);
      if (d.id) byId[d.id] = el;
    });

    // связи между деталями — ортогональные пунктиры
    var conns = Array.isArray(analysis && analysis.connections) ? analysis.connections : [];
    conns.slice(0, 3).forEach(function (c) {
      var a = byId[c && c.from_id];
      var b = byId[c && c.to_id];
      if (!a || !b) return;
      out.push({
        type: 'aiLink',
        ax: a.x + a.w / 2,
        ay: a.y + a.h / 2,
        bx: b.x + b.w / 2,
        by: b.y + b.h / 2,
        raw: { ax: a.x + a.w / 2, ay: a.y + a.h / 2, bx: b.x + b.w / 2, by: b.y + b.h / 2 },
        dashed: c.style === 'dashed_line',
        fromAi: true
      });
    });

    // линии перспективы
    var persp = Array.isArray(analysis && analysis.perspective_lines) ? analysis.perspective_lines : [];
    persp.slice(0, 3).forEach(function (p) {
      if (!p || !Array.isArray(p.points) || p.points.length < 2) return;
      out.push({
        type: 'dashedPath',
        pts: p.points.slice(0, 4).map(function (pt) {
          return {
            x: clamp((Number(pt[0]) / 1000) * W, 0, W),
            y: clamp((Number(pt[1]) / 1000) * H, 0, H)
          };
        }),
        fromAi: true
      });
    });

    // крупный заголовок
    var hc = analysis && analysis.headline_caption;
    if (hc && (hc.text_line_1 || hc.text_line_2)) {
      var anchor = Array.isArray(hc.anchor_box) ? hc.anchor_box : [80, 80, 200, 400];
      var ax = clamp((Number(anchor[1]) / 1000) * W, 0, W * 0.6);
      var ay = clamp((Number(anchor[0]) / 1000) * H, 0, H * 0.7);
      out.push({
        type: 'aiHeadline',
        x: ax,
        y: ay,
        l1: sanitize(hc.text_line_1),
        l2: sanitize(hc.text_line_2),
        fromAi: true
      });
    }

    return out;
  }

  /* ------------------------------ отрисовка ------------------------------ */

  function drawBrackets(x, y, w, h, len, lw) {
    ctx.save();
    ctx.lineWidth = lw;
    ctx.setLineDash([]);
    var corners = [
      [x, y, 1, 1],
      [x + w, y, -1, 1],
      [x, y + h, 1, -1],
      [x + w, y + h, -1, -1]
    ];
    corners.forEach(function (c) {
      ctx.beginPath();
      ctx.moveTo(c[0], c[1] + c[3] * len);
      ctx.lineTo(c[0], c[1]);
      ctx.lineTo(c[0] + c[2] * len, c[1]);
      ctx.stroke();
    });
    ctx.restore();
  }

  function fitFont(text, maxWidth, startSize) {
    var fs = startSize;
    ctx.font = '700 ' + fs + 'px Inter, Arial, sans-serif';
    while (fs > 10 && ctx.measureText(text).width > maxWidth) {
      fs -= 1;
      ctx.font = '700 ' + fs + 'px Inter, Arial, sans-serif';
    }
    return fs;
  }

  // геометрия подписи на выбранной стороне рамки
  function captionGeometry(el, side, fs, tw) {
    var W = canvas.width;
    var H = canvas.height;
    var g = { side: side, align: 'center', fits: false };

    if (side === 'top') {
      g.tx = el.x + el.w / 2;
      g.ty = el.y - 10;
      g.fits = el.y - 10 - fs > 4 && g.tx - tw / 2 > 4 && g.tx + tw / 2 < W - 4;
    } else if (side === 'bottom') {
      g.tx = el.x + el.w / 2;
      g.ty = el.y + el.h + fs + 8;
      g.align = 'center';
      g.fits = g.ty < H - 4 && g.tx - tw / 2 > 4 && g.tx + tw / 2 < W - 4;
    } else if (side === 'left') {
      g.tx = el.x - 8;
      g.ty = el.y + el.h / 2 + fs * 0.35;
      g.align = 'right';
      g.fits = g.tx - tw > 4;
    } else {
      g.side = 'right';
      g.tx = el.x + el.w + 8;
      g.ty = el.y + el.h / 2 + fs * 0.35;
      g.align = 'left';
      g.fits = g.tx + tw < W - 4;
    }
    return g;
  }

  var OPPOSITE = { top: 'bottom', bottom: 'top', left: 'right', right: 'left' };

  function drawCaption(el, baseFont) {
    var W = canvas.width;
    var H = canvas.height;
    if (!el.caption) return;

    var fs = fitFont(el.caption, W * 0.52, Math.max(11, Math.round(baseFont * 0.5)));
    var tw = ctx.measureText(el.caption).width;
    var wish = el.side || 'bottom';
    var order = [wish, OPPOSITE[wish], 'top', 'bottom', 'right', 'left'];

    var g = null;
    for (var i = 0; i < order.length; i++) {
      var cand = captionGeometry(el, order[i], fs, tw);
      if (cand.fits) {
        g = cand;
        break;
      }
    }
    if (!g) {
      // ни одна сторона не свободна — ставим на заказанную и поджимаем внутрь кадра
      g = captionGeometry(el, wish, fs, tw);
      if (g.align === 'center') g.tx = clamp(g.tx, tw / 2 + 6, W - tw / 2 - 6);
      else if (g.align === 'right') g.tx = Math.max(tw + 6, g.tx);
      else g.tx = Math.min(W - tw - 6, g.tx);
      g.ty = clamp(g.ty, fs + 4, H - 6);
    }

    // короткий вынос от рамки к подписи
    var prevColor = ctx.strokeStyle;
    ctx.beginPath();
    if (g.side === 'top' || g.side === 'bottom') {
      var anchorY = g.side === 'top' ? el.y : el.y + el.h;
      var dir = g.side === 'top' ? -1 : 1;
      ctx.moveTo(el.x + el.w / 2, anchorY);
      ctx.lineTo(el.x + el.w / 2, anchorY + dir * 5);
    } else {
      var anchorX = g.side === 'left' ? el.x : el.x + el.w;
      var dirX = g.side === 'left' ? -1 : 1;
      ctx.moveTo(anchorX, el.y + el.h / 2);
      ctx.lineTo(anchorX + dirX * 5, el.y + el.h / 2);
    }
    ctx.stroke();

    ctx.font = '700 ' + fs + 'px Inter, Arial, sans-serif';
    ctx.textAlign = g.align;
    ctx.textBaseline = 'alphabetic';
    ctx.setLineDash([]);

    // тёмная обводка — чтобы подпись читалась поверх светлых участков фото
    var prevWidth = ctx.lineWidth;
    ctx.lineWidth = Math.max(2, fs * 0.22);
    ctx.strokeStyle = 'rgba(4,4,7,.82)';
    ctx.strokeText(el.caption, g.tx, g.ty);
    ctx.lineWidth = prevWidth;
    ctx.strokeStyle = prevColor;

    ctx.fillText(el.caption, g.tx, g.ty);
  }

  function drawAiBox(el, baseFont) {
    var W = canvas.width;
    var lw = Math.max(2, W * 0.0035);
    var g = el.graphic;
    ctx.lineWidth = lw;

    if (g === 'bracket_frame') {
      drawBrackets(el.x, el.y, el.w, el.h, Math.min(el.w, el.h) * 0.3, lw);
    } else if (g === 'puddle_outline') {
      ctx.setLineDash([6, 7]);
      ctx.beginPath();
      ctx.ellipse(el.x + el.w / 2, el.y + el.h / 2, el.w / 2, el.h / 2, 0, 0, Math.PI * 2);
      ctx.stroke();
    } else if (g === 'dashed_contour') {
      ctx.setLineDash([12, 10]);
      ctx.strokeRect(el.x, el.y, el.w, el.h);
      ctx.setLineDash([]);
    } else if (g === 'center_glyph') {
      ctx.strokeRect(el.x, el.y, el.w, el.h);
      var cx = el.x + el.w / 2;
      var cy = el.y + el.h / 2;
      var r = Math.min(el.w, el.h) * 0.12;
      ctx.setLineDash([]);
      ctx.beginPath();
      ctx.moveTo(cx - r, cy);
      ctx.lineTo(cx + r, cy);
      ctx.moveTo(cx, cy - r);
      ctx.lineTo(cx, cy + r);
      ctx.stroke();
      ctx.beginPath();
      ctx.arc(cx, cy, r * 1.7, 0, Math.PI * 2);
      ctx.stroke();
    } else {
      ctx.setLineDash([]);
      ctx.strokeRect(el.x, el.y, el.w, el.h);
    }

    // номер детали у верхнего левого угла
    if (el.index) {
      var fs = Math.max(9, Math.round(baseFont * 0.4));
      ctx.setLineDash([]);
      ctx.font = '700 ' + fs + 'px Inter, Arial, sans-serif';
      ctx.textAlign = 'left';
      ctx.textBaseline = 'alphabetic';
      ctx.fillText(String(el.index).padStart(2, '0'), el.x + 2, clamp(el.y - 4, fs + 2, canvas.height - 4));
    }

    drawCaption(el, baseFont);
  }

  function drawAiHeadline(el, baseFont) {
    var W = canvas.width;
    var H = canvas.height;
    var fs1 = fitFont(el.l1 || '', W * 0.7, Math.round(baseFont * 1.15));
    var fs2 = Math.round(fs1 * 0.62);
    var tx = clamp(el.x, 6, W * 0.6);
    var ty = clamp(el.y, fs1 + 8, H * 0.85);

    ctx.textAlign = 'left';
    ctx.setLineDash([]);
    if (el.l1) {
      ctx.font = '800 ' + fs1 + 'px Inter, Arial, sans-serif';
      ctx.fillText(el.l1, tx, ty);
    }
    if (el.l2) {
      ctx.font = 'italic 500 ' + fs2 + 'px Georgia, "Times New Roman", serif';
      ctx.fillText(el.l2, tx, ty + fs2 + 6);
      // тонкая подчёркивающая линия под второй строкой
      var w2 = ctx.measureText(el.l2).width;
      ctx.lineWidth = Math.max(1.5, W * 0.0022);
      ctx.beginPath();
      ctx.moveTo(tx, ty + fs2 + 12);
      ctx.lineTo(tx + w2, ty + fs2 + 12);
      ctx.stroke();
    }
  }

  function drawAiLink(el) {
    var midX = el.bx;
    var midY = el.ay;
    ctx.setLineDash(el.dashed ? [8, 7] : []);
    ctx.beginPath();
    ctx.moveTo(el.ax, el.ay);
    ctx.lineTo(midX, midY);
    ctx.lineTo(el.bx, el.by);
    ctx.stroke();
    drawArrowHead(midX, midY, el.bx, el.by, 10);
  }

  // вызывается из render() основного скрипта
  window.drawAiElement = function (el, baseFont) {
    if (el.type === 'aiBox') drawAiBox(el, baseFont);
    else if (el.type === 'aiHeadline') drawAiHeadline(el, baseFont);
    else if (el.type === 'aiLink') drawAiLink(el);
  };

  // вызывается из hitTest() основного скрипта — рамки можно таскать мышкой
  window.hitTestAi = function (pos) {
    for (var i = elements.length - 1; i >= 0; i--) {
      var el = elements[i];
      if (el.type === 'aiBox') {
        if (
          pos.x >= el.x - 6 &&
          pos.x <= el.x + el.w + 6 &&
          pos.y >= el.y - 6 &&
          pos.y <= el.y + el.h + 6
        ) {
          return { el: el, handle: el, offset: { x: pos.x - el.x, y: pos.y - el.y } };
        }
      } else if (el.type === 'aiHeadline') {
        if (Math.hypot(pos.x - el.x, pos.y - el.y) < 90) {
          return { el: el, handle: el, offset: { x: pos.x - el.x, y: pos.y - el.y } };
        }
      }
    }
    return null;
  };

  /* ------------------------------ сценарий ------------------------------ */

  function setBusy(v) {
    busy = v;
    var btns = document.querySelectorAll('.toolbar button');
    for (var i = 0; i < btns.length; i++) {
      if (btns[i].getAttribute('onclick') === 'smartAnalyze()') {
        btns[i].disabled = v;
        btns[i].style.opacity = v ? '0.55' : '1';
      }
    }
  }

  window.smartAnalyze = async function () {
    if (busy) return;
    if (!baseImage) {
      toast('Сначала загрузите фото кнопкой «Загрузить фото».', 'warn');
      return;
    }

    setBusy(true);
    toast('Gemini смотрит на фото…', 'ok', 0);

    try {
      var res = await fetch('/api/analyze', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          imageBase64: compressImage(baseImage, 1024, 0.85),
          mimeType: 'image/jpeg',
          variantSeed: Math.floor(Math.random() * 4),
          langMode: currentLang()
        })
      });

      var payload = null;
      try {
        payload = await res.json();
      } catch (e) {
        payload = null;
      }

      if (!res.ok || !payload || !payload.analysis) {
        var msg = (payload && payload.error) || 'HTTP ' + res.status;
        throw new Error(msg);
      }

      var els = buildElements(payload.analysis);
      if (!els.length) throw new Error('модель не нашла деталей на фото');

      elements = els;
      render();
      var n = payload.analysis.detections ? payload.analysis.detections.length : 0;
      toast('Готово: ' + n + ' деталей от Gemini' + (payload.source === 'mock' ? ' (тестовый режим)' : ''), 'ok', 4000);
    } catch (err) {
      hideToast();
      toast('Gemini не ответил (' + err.message + '). Включил локальный режим.', 'warn', 6500);
      try {
        localGenerate();
      } catch (e2) {
        /* ничего не поделать */
      }
    } finally {
      setBusy(false);
    }
  };

  // двойной клик по рамке/заголовку — правим текст
  canvas.addEventListener('dblclick', function (e) {
    var pos = getCanvasCoords(e);
    var hit = window.hitTestAi(pos);
    if (!hit) return;
    var el = hit.el;
    if (el.type === 'aiBox') {
      var v = prompt('Подпись к рамке:', el.caption || '');
      if (v !== null) el.caption = v.trim();
    } else if (el.type === 'aiHeadline') {
      var t = prompt('Заголовок (перенос строки = Enter):', (el.l1 || '') + '\n' + (el.l2 || ''));
      if (t !== null) {
        var parts = t.split('\n');
        el.l1 = (parts[0] || '').trim();
        el.l2 = (parts.slice(1).join(' ') || '').trim();
      }
    }
    render();
  });

  /* --------------------------- язык подписей --------------------------- */

  var LANG_KEY = 'drezzdon_lang_v1';
  var langSel = document.getElementById('captionLang');

  function currentLang() {
    return langSel && langSel.value === 'ru' ? 'ru' : 'drezzdon_en';
  }

  if (langSel) {
    try {
      var savedLang = localStorage.getItem(LANG_KEY);
      if (savedLang === 'ru' || savedLang === 'drezzdon_en') langSel.value = savedLang;
    } catch (e) {
      /* приватный режим — не страшно */
    }
    langSel.addEventListener('change', function () {
      try {
        localStorage.setItem(LANG_KEY, langSel.value);
      } catch (e) {
        /* ignore */
      }
    });
  }

  /* ------------------- память о последнем фото (на устройстве) ------------------- */

  var PHOTO_KEY = 'drezzdon_last_photo_v1';

  window.onPhotoLoaded = function () {
    if (!baseImage) return;
    try {
      localStorage.setItem(PHOTO_KEY, compressImage(baseImage, 1000, 0.82));
    } catch (e) {
      /* не влезло в хранилище — просто не запоминаем */
    }
  };

  function restorePhoto() {
    var saved = null;
    try {
      saved = localStorage.getItem(PHOTO_KEY);
    } catch (e) {
      return;
    }
    if (!saved) return;

    var img = new Image();
    img.onload = function () {
      var maxDim = 1000;
      var w = img.width;
      var h = img.height;
      if (w > maxDim || h > maxDim) {
        if (w > h) {
          h = Math.round((h * maxDim) / w);
          w = maxDim;
        } else {
          w = Math.round((w * maxDim) / h);
          h = maxDim;
        }
      }
      canvas.width = w;
      canvas.height = h;
      baseImage = img;
      try {
        localGenerate();
      } catch (e) {
        render();
      }
      toast('Прошлое фото восстановлено. Жмите ⚡, чтобы прогнать через Gemini.', 'ok', 5000);
    };
    img.src = saved;
  }

  restorePhoto();
})();
